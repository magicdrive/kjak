#!/bin/sh
# Writes the Homebrew formula of a release to standard output, from the
# checksums.txt of its archives (the file that is published with them):
#
#   scripts/formula.sh [--snapshot] DIST [TAG]
#
# --snapshot accepts the version of a local snapshot build (X.Y.Z-snapshot,
# `make snapshot`); the release workflow never passes it.
# DIST holds checksums.txt; TAG (vX.Y.Z) is the release tag, else it is read
# from the archive names. The URLs are those of the GitHub release of TAG.
# The formula installs the binary only (README and LICENSE stay in the
# archive). It is published by the release workflow after the release. A
# pre-release (vX.Y.Z-rc.1) gets no formula.
set -eu

snapshot=no
if [ "${1:-}" = --snapshot ]; then
	snapshot=yes
	shift
fi
dist=${1:?usage: formula.sh [--snapshot] DIST [TAG]}
sums="$dist/checksums.txt"
fail() { echo "formula: $*" >&2; exit 1; }
[ -f "$sums" ] || fail "no $sums"

version=$(awk '{ print $2 }' "$sums" | sed -n 's/^kjak_\(.*\)_darwin_arm64\.tar\.gz$/\1/p')
[ -n "$version" ] || fail "no darwin_arm64 archive in $sums"
tag=${2:-v$version}
[ "$tag" = "v$version" ] || fail "tag $tag does not match the archives (v$version)"
case "$version" in
	*-snapshot) [ "$snapshot" = yes ] || fail "$tag is a snapshot: pass --snapshot for a local formula" ;;
	*-*) fail "$tag is a pre-release: the Homebrew formula follows releases only" ;;
esac
base="https://github.com/magicdrive/kjak/releases/download/$tag"

sha() {
	s=$(awk -v f="kjak_${version}_$1.tar.gz" '$2 == f { print $1 }' "$sums")
	printf '%s' "$s" | grep -Eq '^[0-9a-f]{64}$' || fail "no SHA-256 for kjak_${version}_$1.tar.gz"
	printf '%s' "$s"
}
darwin_arm64=$(sha darwin_arm64)
darwin_amd64=$(sha darwin_amd64)
linux_arm64=$(sha linux_arm64)
linux_amd64=$(sha linux_amd64)

cat <<FORMULA
# typed: false
# frozen_string_literal: true

# Generated by scripts/formula.sh of magicdrive/kjak for $tag. Do not edit.
class Kjak < Formula
  desc "Deliver notifications to Slack, Discord and e-mail"
  homepage "https://github.com/magicdrive/kjak"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/kjak_${version}_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/kjak_${version}_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/kjak_${version}_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/kjak_${version}_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "kjak"
  end

  test do
    assert_match "kjak version $tag", shell_output("#{bin}/kjak version")
  end
end
FORMULA
